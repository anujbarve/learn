#!/usr/bin/env bash
# install.sh — wire the learn system into a project for one or more coding-agent CLIs.
#
#   ./learn/install.sh [--target DIR] [--force] <harness>...
#
# harness: claude | gemini | opencode | codex | freebuff | agy (Antigravity) | pi | all
#
# --target  project root to install into (default: current directory)
# --force   overwrite generated agent files even if they were edited
#
# Skills and AGENTS.md are symlinked, so `git pull` inside learn/ updates every
# harness at once. Subagent files are generated, because each CLI wants its own
# frontmatter. Re-run install.sh after pulling to refresh them.
set -euo pipefail

LEARN="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
TARGET="$PWD"
FORCE=0
HARNESSES=()
MARK="generated by learn/install.sh"

die() { echo "error: $*" >&2; exit 1; }
say() { echo "  $*"; }

while [ $# -gt 0 ]; do
  case "$1" in
    --target) TARGET="$2"; shift 2 ;;
    --force) FORCE=1; shift ;;
    -h|--help) sed -n 2,14p "$0"; exit 0 ;;
    all) HARNESSES+=(claude gemini opencode codex freebuff agy); shift ;;
    antigravity) HARNESSES+=(agy); shift ;;
    claude|gemini|opencode|codex|freebuff|agy|pi) HARNESSES+=("$1"); shift ;;
    *) die "unknown argument: $1 (try --help)" ;;
  esac
done
[ ${#HARNESSES[@]} -gt 0 ] || die "name at least one harness: claude gemini opencode codex freebuff agy pi all"
[ -d "$TARGET" ] || die "target not found: $TARGET"
TARGET="$(cd "$TARGET" && pwd -P)"
[ "$TARGET" != "$LEARN" ] || die "run this from your learning project's root, not from inside learn/ (or pass --target)"

# Path of learn/ relative to the target, so symlinks survive moving the project.
REL="$(python3 -c 'import os,sys;print(os.path.relpath(sys.argv[1],sys.argv[2]))' "$LEARN" "$TARGET" 2>/dev/null || echo "$LEARN")"

link() { # link <dest relative to target> <source relative to learn>
  local dest="$TARGET/$1" depth up src
  depth="$(dirname "$1" | awk -F/ '$0=="."{print 0;next}{print NF}')"
  up=""; for ((i=0;i<depth;i++)); do up="../$up"; done
  case "$REL" in /*) src="$REL/$2" ;; *) src="$up$REL/$2" ;; esac
  mkdir -p "$(dirname "$dest")"
  if [ -L "$dest" ]; then rm "$dest"
  elif [ -e "$dest" ]; then say "skip $1 (exists, not a symlink)"; return; fi
  ln -s "$src" "$dest"; say "link $1 -> $src"
}

ensure_import() { # ensure_import <file> <line>: create file or append line once
  local f="$TARGET/$1"
  if [ -f "$f" ] && grep -qxF "$2" "$f"; then say "ok   $1"; return; fi
  if [ -f "$f" ]; then printf '\n%s\n' "$2" >> "$f"; say "edit $1 (appended '$2')"
  else printf '%s\n' "$2" > "$f"; say "new  $1"; fi
}

agents_md() {
  local f="$TARGET/AGENTS.md"
  if [ ! -e "$f" ] || [ -L "$f" ]; then link AGENTS.md AGENTS.md; return; fi
  if grep -q "learn:begin" "$f"; then say "ok   AGENTS.md"; return; fi
  printf '\n<!-- learn:begin -->\n## Learning system\n\nRead and follow `%s/AGENTS.md`. Its skills live in `%s/skills/`.\n<!-- learn:end -->\n' "$REL" "$REL" >> "$f"
  say "edit AGENTS.md (appended pointer to $REL/AGENTS.md)"
}

skills_into() { link "$1/teach" skills/teach; link "$1/visualize" skills/visualize; }

field() { awk -v k="$1" 'NR==1&&/^---$/{f=1;next} f&&/^---$/{exit} f&&index($0,k": ")==1{sub("^"k": ","");print}' "$2"; }
body() { awk 'NR==1&&/^---$/{f=1;next} f==1&&/^---$/{f=2;next} f!=1{print}' "$1" | sed "s|{{LEARN_DIR}}|$LEARN|g"; }
yq() { local s="${1#\"}"; s="${s%\"}"; s="${s//\\/\\\\}"; printf '"%s"' "${s//\"/\\\"}"; }

gen_agent() { # gen_agent <harness> <dir> <name>
  local h="$1" dir="$2" name="$3" src="$LEARN/agents/$3.md" out desc
  out="$TARGET/$dir/$name.md"
  if [ -f "$out" ] && [ $FORCE -eq 0 ] && ! grep -q "$MARK" "$out"; then
    say "skip $dir/$name.md (hand-edited; use --force)"; return
  fi
  desc="$(yq "$(field description "$src")")"
  mkdir -p "$TARGET/$dir"
  {
    echo "---"
    case "$h" in
      claude)
        echo "name: $name"; echo "description: $desc"
        if [ "$name" = researcher ]; then echo "tools: WebSearch, WebFetch, Read, Grep, Glob"
        else echo "tools: Read, Write, Edit, Bash"; fi
        echo "model: sonnet" ;;
      opencode)
        echo "description: $desc"; echo "mode: subagent"; echo "permission:"
        if [ "$name" = researcher ]; then printf '  edit: deny\n  bash: deny\n  webfetch: allow\n'
        else printf '  edit: allow\n  bash: allow\n  webfetch: deny\n'; fi ;;
      gemini)
        echo "name: $name"; echo "description: $desc" ;;
    esac
    echo "---"
    echo "<!-- $MARK from agents/$name.md — edit the source and re-run install.sh -->"
    body "$src"
  } > "$out"
  say "gen  $dir/$name.md"
}

all_agents() { for a in researcher mermaid-maker svg-maker; do gen_agent "$1" "$2" "$a"; done; }

echo "Installing learn ($LEARN) into $TARGET"
did_common=0
common() { [ $did_common -eq 1 ] && return; did_common=1; agents_md; skills_into .agents/skills; }

for h in "${HARNESSES[@]}"; do
  echo "[$h]"
  case "$h" in
    claude)
      agents_md
      skills_into .claude/skills
      ensure_import CLAUDE.md "@AGENTS.md"
      all_agents claude .claude/agents ;;
    gemini)
      common
      ensure_import GEMINI.md "@AGENTS.md"
      all_agents gemini .gemini/agents
      say "note Gemini subagents may need enabling in .gemini/settings.json (see Gemini CLI docs for your version)" ;;
    opencode)
      common
      all_agents opencode .opencode/agents ;;
    codex|freebuff|agy)
      common
      say "note no project subagents here; the agent runs researcher/maker workflows inline" ;;
    pi)
      if [ -e "$TARGET/.pi" ] && [ ! -L "$TARGET/.pi" ]; then
        say "skip .pi (exists). Copy or link skills/, agents/, extensions/ into it by hand."
      else link .pi .; fi
      say "note run: (cd $LEARN/extensions/visual-tools && npm install) for rendered visuals" ;;
  esac
done
echo "Done."
